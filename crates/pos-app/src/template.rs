//! Business templates: the starting points the setup wizard offers (a café,
//! a shop, a restaurant…), read from the JSON files in `templates/`.
//!
//! Templates are data, not code, so a fork can add its own by adding a file.
//! See `templates/README.md` for the format.

use std::collections::HashMap;

use pos_core::{
    catalog::{ItemKind, ModePreset, ModifierGroup},
    ids::ModifierGroupId,
    money::{Currency, Money},
};
use serde::Deserialize;

use crate::{AppError, BusinessSetup, Register, Result, StaffRole, modifier, simple_item, variant};

/// Every template file, as `(id, json)`. Generated by `build.rs`.
const FILES: &[(&str, &str)] = include!(concat!(env!("OUT_DIR"), "/templates.rs"));

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Template {
    #[serde(skip)]
    pub id: String,
    pub name: String,
    #[serde(default)]
    pub description: String,
    #[serde(default)]
    pub sort: i32,
    pub areas: Vec<Area>,
    #[serde(default)]
    pub option_groups: Vec<OptionGroup>,
    #[serde(default)]
    pub items: Vec<TemplateItem>,
    #[serde(default)]
    pub staff: Vec<TemplateStaff>,
    /// Present on demo templates: everything needed to set up in one tap.
    pub demo: Option<Demo>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Area {
    pub name: String,
    pub mode: Mode,
}

#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum Mode {
    Retail,
    QuickService,
    FullService,
    Bar,
}

impl From<Mode> for ModePreset {
    fn from(m: Mode) -> Self {
        match m {
            Mode::Retail => ModePreset::Retail,
            Mode::QuickService => ModePreset::QuickService,
            Mode::FullService => ModePreset::FullService,
            Mode::Bar => ModePreset::Bar,
        }
    }
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct OptionGroup {
    pub name: String,
    #[serde(default)]
    pub min: u8,
    pub max: u8,
    /// `[name, price]` pairs.
    pub options: Vec<(String, String)>,
}

#[derive(Debug, Clone, Copy, Default, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum Kind {
    #[default]
    MenuItem,
    Product,
    Service,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TemplateItem {
    pub name: String,
    pub area: String,
    pub price: String,
    #[serde(default)]
    pub kind: Kind,
    #[serde(default)]
    pub sizes: Vec<(String, String)>,
    /// Option group names.
    #[serde(default)]
    pub options: Vec<String>,
    pub stock: Option<i64>,
    #[serde(default)]
    pub age_restricted: bool,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TemplateStaff {
    pub name: String,
    pub role: Role,
    pub pin: String,
}

#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum Role {
    Cashier,
    Manager,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Demo {
    pub business_name: String,
    pub currency: String,
    pub owner_name: String,
    pub owner_pin: String,
    pub tax: Option<Tax>,
    pub order_prefix: String,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Tax {
    pub name: String,
    /// e.g. "8.25".
    pub percent: String,
    pub included: bool,
}

/// Every template, sorted for display. Broken files are a build-time test
/// failure (see the tests below), so they're skipped here rather than
/// crashing the wizard.
pub fn all() -> Vec<Template> {
    let mut out: Vec<Template> = FILES.iter().filter_map(|(id, _)| get(id).ok()).collect();
    out.sort_by(|a, b| (a.sort, &a.name).cmp(&(b.sort, &b.name)));
    out
}

pub fn get(id: &str) -> Result<Template> {
    let (_, json) =
        FILES.iter().find(|(i, _)| *i == id).ok_or(AppError::NotFound("business template"))?;
    let mut t: Template = serde_json::from_str(json)
        .map_err(|e| AppError::Rejected(format!("template {id} is broken: {e}")))?;
    t.id = id.to_string();
    t.validate()?;
    Ok(t)
}

/// Parses a plain decimal ("4.75", "12", "0.5") into the currency's minor
/// units, rounding half up to the currency's precision.
pub fn parse_amount(text: &str, currency: Currency) -> Result<Money> {
    let bad = || AppError::Rejected(format!("{text:?} isn't an amount"));
    let text = text.trim();
    let (negative, digits) = match text.strip_prefix('-') {
        Some(rest) => (true, rest),
        None => (false, text),
    };
    let (whole, frac) = digits.split_once('.').unwrap_or((digits, ""));
    if whole.is_empty() && frac.is_empty()
        || !whole.chars().all(|c| c.is_ascii_digit())
        || !frac.chars().all(|c| c.is_ascii_digit())
        || frac.len() > 9
    {
        return Err(bad());
    }
    let exp = usize::from(currency.exponent());
    let whole: i64 = if whole.is_empty() { 0 } else { whole.parse().map_err(|_| bad())? };
    let mut frac = frac.to_string();
    let round_up = frac.len() > exp && frac.as_bytes()[exp] >= b'5';
    frac.truncate(exp);
    while frac.len() < exp {
        frac.push('0');
    }
    let frac: i64 = if frac.is_empty() { 0 } else { frac.parse().map_err(|_| bad())? };
    let scale = 10i64.pow(u32::from(currency.exponent()));
    let minor = whole
        .checked_mul(scale)
        .and_then(|w| w.checked_add(frac))
        .and_then(|m| m.checked_add(i64::from(round_up)))
        .ok_or_else(bad)?;
    Ok(Money::from_minor(if negative { -minor } else { minor }, currency))
}

/// Parses a percentage ("8.25") into basis points (825).
pub fn parse_percent(text: &str) -> Result<i32> {
    let bp = parse_amount(text, Currency::new(*b"PCT", 2))?.minor();
    i32::try_from(bp)
        .ok()
        .filter(|bp| (0..=10_000).contains(bp))
        .ok_or_else(|| AppError::Rejected(format!("{text}% isn't a tax rate")))
}

impl Template {
    fn validate(&self) -> Result<()> {
        let bad = |why: String| Err(AppError::Rejected(format!("template {}: {why}", self.id)));
        if self.areas.is_empty() {
            return bad("needs at least one area".into());
        }
        for item in &self.items {
            if !self.areas.iter().any(|a| a.name == item.area) {
                return bad(format!("{} is in unknown area {}", item.name, item.area));
            }
            for o in &item.options {
                if !self.option_groups.iter().any(|g| &g.name == o) {
                    return bad(format!("{} uses unknown options {o}", item.name));
                }
            }
            if item.stock.is_some() && item.kind != Kind::Product {
                return bad(format!("{} has stock but isn't a product", item.name));
            }
        }
        for g in &self.option_groups {
            if g.max == 0 || g.min > g.max || usize::from(g.min) > g.options.len() {
                return bad(format!("option group {} has impossible limits", g.name));
            }
        }
        if let Some(demo) = &self.demo {
            currency(&demo.currency)?;
            if let Some(t) = &demo.tax {
                parse_percent(&t.percent)?;
            }
        }
        Ok(())
    }

    /// The business setup for a demo template.
    pub fn demo_setup(&self) -> Result<BusinessSetup> {
        let demo = self.demo.as_ref().ok_or(AppError::Invalid("not a demo template"))?;
        Ok(BusinessSetup {
            business_name: demo.business_name.clone(),
            currency: currency(&demo.currency)?,
            owner_name: demo.owner_name.clone(),
            owner_pin: demo.owner_pin.clone(),
            revenue_centers: self.areas(),
            tax: match &demo.tax {
                Some(t) => Some((t.name.clone(), parse_percent(&t.percent)?, t.included)),
                None => None,
            },
            order_prefix: demo.order_prefix.clone(),
        })
    }

    /// The selling areas, ready for [`BusinessSetup::revenue_centers`].
    pub fn areas(&self) -> Vec<(String, ModePreset)> {
        self.areas.iter().map(|a| (a.name.clone(), a.mode.into())).collect()
    }

    /// Adds the template's option groups, items, stock and (demo) staff to a
    /// newly created business. The owner must be signed in.
    pub fn apply(&self, reg: &mut Register) -> Result<()> {
        self.apply_catalog(reg)?;
        for s in &self.staff {
            let role = match s.role {
                Role::Cashier => StaffRole::Cashier,
                Role::Manager => StaffRole::Manager,
            };
            reg.add_staff(&s.name, &s.pin, role)?;
        }
        Ok(())
    }

    /// Adds only the sample option groups, items and stock. Real businesses
    /// use this: template staff have well-known PINs, so they're demo-only.
    pub fn apply_catalog(&self, reg: &mut Register) -> Result<()> {
        let currency = reg.currency();
        let centers: HashMap<String, _> =
            reg.revenue_centers().into_iter().map(|c| (c.name.clone(), c.id)).collect();
        let taxes: Vec<_> = reg.taxes().first().map(|t| t.id).into_iter().collect();

        let mut groups: HashMap<&str, ModifierGroupId> = HashMap::new();
        for g in &self.option_groups {
            let group = ModifierGroup {
                id: ModifierGroupId::new(),
                name: g.name.clone(),
                min: g.min,
                max: g.max,
                modifiers: g
                    .options
                    .iter()
                    .map(|(n, p)| Ok(modifier(n, parse_amount(p, currency)?)))
                    .collect::<Result<_>>()?,
            };
            groups.insert(&g.name, group.id);
            reg.save_modifier_group(group)?;
        }
        for t in &self.items {
            let center = *centers.get(&t.area).ok_or(AppError::NotFound("template area"))?;
            let kind = match t.kind {
                Kind::MenuItem => ItemKind::MenuItem,
                Kind::Product => ItemKind::PhysicalGood,
                Kind::Service => ItemKind::Service,
            };
            let mods = t.options.iter().filter_map(|o| groups.get(o.as_str()).copied()).collect();
            let mut item = simple_item(
                &t.name,
                kind,
                parse_amount(&t.price, currency)?,
                center,
                taxes.clone(),
                mods,
            );
            item.age_restricted = t.age_restricted;
            item.variants = t
                .sizes
                .iter()
                .map(|(n, p)| Ok(variant(n, parse_amount(p, currency)?)))
                .collect::<Result<_>>()?;
            let id = item.id;
            reg.save_item(item)?;
            if let Some(stock) = t.stock.filter(|s| *s != 0) {
                reg.receive_stock(id, stock)?;
            }
        }
        Ok(())
    }
}

