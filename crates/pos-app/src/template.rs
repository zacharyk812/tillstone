pub fn currency(code: &str) -> Result<Currency> {
    CURRENCIES
        .iter()
        .find(|(c, _, _)| *c == code)
        .map(|(c, exp, _)| {
            let b = c.as_bytes();
            Currency::new([b[0], b[1], b[2]], *exp)
        })
        .ok_or_else(|| AppError::Rejected(format!("unknown currency {code}")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_template_file_is_valid() {
        assert!(!FILES.is_empty(), "no templates were embedded");
        for (id, _) in FILES {
            get(id).unwrap_or_else(|e| panic!("{id}: {e}"));
        }
        assert_eq!(all().len(), FILES.len());
    }

    #[test]
    fn templates_are_sorted_with_the_demo_first() {
        let all = all();
        assert_eq!(all[0].id, "demo");
        assert!(all.windows(2).all(|w| w[0].sort <= w[1].sort));
    }

    #[test]
    fn amounts_parse_into_minor_units() {
        let usd = Currency::USD;
        assert_eq!(parse_amount("4.75", usd).unwrap().minor(), 475);
        assert_eq!(parse_amount("12", usd).unwrap().minor(), 1200);
        assert_eq!(parse_amount("0.5", usd).unwrap().minor(), 50);
        assert_eq!(parse_amount(".25", usd).unwrap().minor(), 25);
        assert_eq!(parse_amount("1.005", usd).unwrap().minor(), 101);
        assert_eq!(parse_amount("-3.10", usd).unwrap().minor(), -310);
        assert_eq!(parse_amount("4.75", Currency::JPY).unwrap().minor(), 5);
        assert_eq!(parse_amount("1.5", Currency::KWD).unwrap().minor(), 1500);
        for bad in ["", ".", "abc", "1.2.3", "1,50", "--1", "99999999999999999999"] {
            assert!(parse_amount(bad, usd).is_err(), "{bad:?}");
        }
    }

    #[test]
    fn percentages_parse_into_basis_points() {
        assert_eq!(parse_percent("8.25").unwrap(), 825);
        assert_eq!(parse_percent("20").unwrap(), 2000);
        assert_eq!(parse_percent("0").unwrap(), 0);
        assert!(parse_percent("101").is_err());
        assert!(parse_percent("-1").is_err());
    }

    #[test]
    fn currencies_are_unique_and_known() {
        let mut codes: Vec<_> = CURRENCIES.iter().map(|c| c.0).collect();
        codes.sort_unstable();
        codes.dedup();
        assert_eq!(codes.len(), CURRENCIES.len());
        assert_eq!(currency("JPY").unwrap().exponent(), 0);
        assert!(currency("XXX").is_err());
    }
}
